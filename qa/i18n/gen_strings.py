"""Generate platform string tables from qa/i18n/strings_en.py (single English source of truth).

Outputs:
  apps/android/app/src/main/res/values/strings.xml   (Android resources)
  apps/ios/App/Localizable.xcstrings                 (iOS String Catalog, source language en)

Usage: python3 qa/i18n/gen_strings.py [--check]
--check exits non-zero if any Android R.string/R.plurals or iOS L10n key is missing or unused.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).parent))
from strings_en import P, S  # noqa: E402

ANDROID = ROOT / "apps/android/app/src/main/res/values/strings.xml"
IOS = ROOT / "apps/ios/App/Localizable.xcstrings"
IOS_FALLBACK = ROOT / "apps/ios/Sources/MeetSaathiKit/Core/L10nEnglish.swift"


def android_escape(v: str) -> str:
    v = v.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    v = v.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
    if v.startswith("@") or v.startswith("?"):
        v = "\\" + v
    return v


def has_args(v: str) -> bool:
    return re.search(r"%\d+\$", v) is not None


def write_android() -> None:
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- GENERATED by qa/i18n/gen_strings.py from qa/i18n/strings_en.py. Edit the source, not this file. -->",
             "<resources>"]
    for k, v in S.items():
        attr = "" if has_args(v) else ' formatted="false"' if "%" in v else ""
        lines.append(f'    <string name="{k}"{attr}>{android_escape(v)}</string>')
    for k, (one, other) in P.items():
        lines.append(f'    <plurals name="{k}">')
        lines.append(f'        <item quantity="one">{android_escape(one)}</item>')
        lines.append(f'        <item quantity="other">{android_escape(other)}</item>')
        lines.append("    </plurals>")
    lines.append("</resources>")
    ANDROID.write_text("\n".join(lines) + "\n", encoding="utf-8")


def ios_value(v: str) -> str:
    # Android positional %1$s / %1$d / %1$.1f map to the same positional printf syntax iOS uses; %s -> %@.
    v = re.sub(r"%(\d+)\$s", r"%\1$@", v)
    return re.sub(r"%(\d+)\$d", r"%\1$ld", v)  # Swift Int is 64-bit


def write_ios() -> None:
    strings = {}
    for k, v in S.items():
        if k.startswith("notif_") or k == "action_stop":
            continue  # Android notification copy
        strings[k] = {"extractionState": "manual", "localizations": {"en": {"stringUnit": {"state": "translated", "value": ios_value(v)}}}}
    for k, (one, other) in P.items():
        strings[k] = {"extractionState": "manual", "localizations": {"en": {"variations": {"plural": {
            "one": {"stringUnit": {"state": "translated", "value": ios_value(one)}},
            "other": {"stringUnit": {"state": "translated", "value": ios_value(other)}}}}}}}
    IOS.write_text(json.dumps({"sourceLanguage": "en", "strings": dict(sorted(strings.items())), "version": "1.0"},
                              ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def swift_lit(v: str) -> str:
    return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_ios_fallback() -> None:
    """English fallback compiled into MeetSaathiKit: used when the app bundle's String Catalog lacks a key (and by swift test)."""
    lines = ["// GENERATED by qa/i18n/gen_strings.py from qa/i18n/strings_en.py. Edit the source, not this file.",
             "// The app's String Catalog (App/Localizable.xcstrings) is authoritative; this is only the English fallback.", "",
             "enum L10nEnglish {", "    static let strings: [String: String] = ["]
    for k, v in S.items():
        if k.startswith("notif_") or k == "action_stop":
            continue
        lines.append(f"        {swift_lit(k)}: {swift_lit(ios_value(v))},")
    lines += ["    ]", "    static let plurals: [String: (one: String, other: String)] = ["]
    for k, (one, other) in P.items():
        lines.append(f"        {swift_lit(k)}: ({swift_lit(ios_value(one))}, {swift_lit(ios_value(other))}),")
    lines += ["    ]", "}", ""]
    IOS_FALLBACK.write_text("\n".join(lines), encoding="utf-8")


def check() -> int:
    used_s, used_p = set(), set()
    for f in (ROOT / "apps/android/app/src/main/java").rglob("*.kt"):
        t = f.read_text()
        used_s |= set(re.findall(r"R\.string\.([a-z0-9_]+)", t))
        used_p |= set(re.findall(r"R\.plurals\.([a-z0-9_]+)", t))
    ios_used = set()
    for f in (ROOT / "apps/ios").rglob("*.swift"):
        ios_used |= set(re.findall(r"\bLP?\(\"([a-z0-9_]+)\"", f.read_text()))
    problems = []
    problems += [f"android missing string: {k}" for k in sorted(used_s - set(S))]
    problems += [f"android missing plural: {k}" for k in sorted(used_p - set(P))]
    problems += [f"ios missing key: {k}" for k in sorted(ios_used - set(S) - set(P))]
    unused = sorted((set(S) - used_s - ios_used) - {"app_name"})
    for p in problems:
        print(p)
    if unused:
        print("unused (informational):", " ".join(unused))
    return 1 if problems else 0


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(check())
    write_android()
    write_ios()
    write_ios_fallback()
    print(f"wrote {ANDROID.relative_to(ROOT)} ({len(S)} strings, {len(P)} plurals) and {IOS.relative_to(ROOT)}")
    sys.exit(check())
